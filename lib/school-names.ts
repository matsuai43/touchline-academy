/** 「都道府県名（コア）＋語尾」のパターン（例: 静岡高校・鹿児島高校）を禁止する。 */
function matchesPrefecturePattern(name: string): boolean {
  const cores = new Set(Object.values(PREFECTURE_CORE_NAMES));
  for (const core of cores) {
    for (const suf of SCHOOL_SUFFIXES) {
      if (name === core + suf) return true;
    }
  }
  return false;
}
export function isBlockedSchoolName(name: string): boolean {
  return BLOCKED_SCHOOL_NAMES.has(name) || matchesPrefecturePattern(name);
}

// ---------------------------------------------------------------------------
// 校名・ユース名の生成（決定的。used に既出の名前を渡すと重複を避けて再試行する）
// ---------------------------------------------------------------------------
function wordsFor(districtId: DistrictId): string[] {
  return DISTRICT_WORDS[districtId] ?? DISTRICT_WORDS.yamagata;
}

/** 地域色のある校名を1つ決定的に作る。seedParts が同じなら常に同じ結果になる。
 *  used が渡されれば、既出・除外リスト該当・都道府県名パターンを避けて別の組み合わせを試す
 *  （最大48試行。それでも空きが無ければ最後の候補をそのまま返す＝実運用では起こらない）。 */
export function regionalSchoolName(
  districtId: DistrictId,
  seedParts: number[],
  used?: ReadonlySet<string>,
): string {
  const words = wordsFor(districtId);
  let candidate = '';
  for (let salt = 0; salt < 48; salt++) {
    const parts = [...seedParts, salt];
    const useDirection = hf(...parts, 11) < 0.22;
    const stem = pickFrom(words, hf(...parts, 12));
    const suffix = pickFrom(SCHOOL_SUFFIXES, hf(...parts, 13));
    const direction = useDirection ? pickFrom(DIRECTION_WORDS, hf(...parts, 14)) : '';
    candidate = `${direction}${stem}${suffix}`;
    if (isBlockedSchoolName(candidate)) continue;
    if (used && used.has(candidate)) continue;
    return candidate;
  }
  return candidate;
}

/** 地域色のあるユースチーム名を1つ決定的に作る（例:「駿河FCユース」）。 */
export function regionalYouthName(
  districtId: DistrictId,
  seedParts: number[],
  used?: ReadonlySet<string>,
): string {
  const words = wordsFor(districtId);
  let candidate = '';
  for (let salt = 0; salt < 48; salt++) {
    const parts = [...seedParts, salt];
    const stem = pickFrom(words, hf(...parts, 21));
    const suffix = pickFrom(YOUTH_SUFFIXES, hf(...parts, 22));
    candidate = `${stem}${suffix}`;
    if (isBlockedYouthName(candidate)) continue;
    if (used && used.has(candidate)) continue;
    return candidate;
  }
  return candidate;
}
